const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('native', {
  isElectron: true,
  settings: (() => { try { return ipcRenderer.sendSync('settings:get'); } catch (e) { return {}; } })(),
  saveSettings: (st) => ipcRenderer.invoke('settings:set', st),
  relaunch: () => ipcRenderer.invoke('app:relaunch'),
  sysInfo: () => ipcRenderer.invoke('sys:info'),
  writeAt: (p, off, d) => ipcRenderer.invoke('fs:writeAt', p, off, d),
  mediaURL: (p) => 'tz://app/media?p=' + encodeURIComponent(p),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch (e) { return null; } },
  openMedia: () => ipcRenderer.invoke('dialog:openMedia'),
  openFolder: () => ipcRenderer.invoke('dialog:openFolder'),
  openProject: () => ipcRenderer.invoke('dialog:openProject'),
  saveDialog: (opts) => ipcRenderer.invoke('dialog:save', opts),
  message: (opts) => ipcRenderer.invoke('dialog:message', opts),
  readText: (p) => ipcRenderer.invoke('fs:readText', p),
  writeText: (p, t) => ipcRenderer.invoke('fs:writeText', p, t),
  writeBinary: (p, d) => ipcRenderer.invoke('fs:writeBinary', p, d),
  append: (p, d) => ipcRenderer.invoke('fs:append', p, d),
  exists: (p) => ipcRenderer.invoke('fs:exists', p),
  unlink: (p) => ipcRenderer.invoke('fs:unlink', p),
  tempPath: (n) => ipcRenderer.invoke('fs:tempPath', n),
  userData: () => ipcRenderer.invoke('fs:userData'),
  showItem: (p) => ipcRenderer.invoke('shell:showItem', p),
  openPath: (p) => ipcRenderer.invoke('shell:openPath', p),
  openExternal: (u) => ipcRenderer.invoke('shell:openExternal', u),
  setTitle: (t) => ipcRenderer.invoke('win:setTitle', t),
  confirmClose: () => ipcRenderer.invoke('win:confirmClose'),
  startupFile: () => ipcRenderer.invoke('app:startupFile'),
  info: () => ipcRenderer.invoke('app:info'),
  engineInfo: () => ipcRenderer.invoke('engine:info'),
  engineStart: (o) => ipcRenderer.invoke('engine:start', o),
  engineWrite: (d) => ipcRenderer.invoke('engine:write', d),
  engineEnd: () => ipcRenderer.invoke('engine:end'),
  engineAbort: () => ipcRenderer.invoke('engine:abort'),
  ffmpeg: (args, jobId) => ipcRenderer.invoke('ffmpeg:run', args, jobId),
  onFfmpegProgress: (cb) => ipcRenderer.on('ffmpeg:progress', (e, id, t) => cb(id, t)),
  onCloseRequest: (cb) => ipcRenderer.on('close-request', () => cb()),
  onOpenProjectFile: (cb) => ipcRenderer.on('open-project-file', (e, f) => cb(f))
});
